"""
The Land page, AS THE NODE SERVES IT, loads every module under exactly one URL — above all three.js.

A browser keys an ES module by its full URL, query included. The node stamps every "/static/…" and "./…" import with
?v=<content hash> (ops/static_versions.py) and leaves bare names alone; three's post-processing add-ons import the core by
the bare names "three/webgpu" / "three/tsl" (land.html's import map). When land.js imported the core by PATH, it was
served as three.webgpu.js?v=… while the add-ons resolved to plain three.webgpu.js: two instances of three, two TSL node
stacks, and the live page drew nothing ("pitch black", 2026-11-06). Every test of the page had served the files
unstamped, where both spellings are one URL — so this test serves them through the real stamper.

  * the page's module graph, walked from land.html's served body with its import map, resolves every import the way a
    browser does (bare names by the map, absolute and relative paths with their stamps);
  * no file in that graph is reached under two different URLs;
  * the graph does reach three's core and every add-on the page draws with (the walk is not vacuous).

Run: python3 tests/test_the_land_page_loads_one_copy_of_three.py
"""
import os, tempfile  # ISOLATION FIRST (CLAUDE.md rule 4)
os.environ["HOME"] = tempfile.mkdtemp(prefix="nado-test-land-one-three-")
import atexit, shutil; atexit.register(shutil.rmtree, os.environ["HOME"], ignore_errors=True)
import json, posixpath, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))
import _harness
from ops.static_versions import StaticVersions   # pure: os/re/hashlib, no node state
_report = _harness.Report()
check = _report.check

STATIC = os.path.join(ROOT, "static")
SV = StaticVersions(STATIC)


def served(path):
    """The bytes the node serves for /static/<path> (rewritten for a page or module, the file itself for a leaf)."""
    got = SV.get(os.path.join(STATIC, path[len("/static/"):]))
    assert got is not None, path
    return got[0] if got[0] is not None else open(os.path.join(STATIC, path[len("/static/"):]), "rb").read()


page = served("/static/land.html").decode()
imap = json.loads(re.search(r'<script type="importmap">(.*?)</script>', page, re.S).group(1))["imports"]
entry = re.search(r'<script type="module" src="([^"]+)"', page).group(1)

# static and dynamic imports: from "x" · import "x" · import("x")
SPEC = re.compile(r'(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["\']([^"\'\s,]+)["\']')
# comments are not imports (nadodapp.js shows its own import line as usage; nado-crypto.js its build recipe)
COMMENTS = re.compile(r'/\*.*?\*/|(?:^|(?<=\s))//[^\n]*', re.S)


def resolve(spec, base_url):
    if spec.startswith("/"):
        return spec
    if spec.startswith("./") or spec.startswith("../"):
        return posixpath.normpath(posixpath.join(posixpath.dirname(base_url.split("?")[0]), spec))
    if spec in imap:
        return imap[spec]
    for k, v in imap.items():
        if k.endswith("/") and spec.startswith(k):
            return v + spec[len(k):]
    return None                                      # a bare name the map does not know: the browser would refuse it


urls_of, todo, seen, unresolved = {}, [entry], set(), []
while todo:
    url = todo.pop()
    if url in seen:
        continue
    seen.add(url)
    path = url.split("?")[0]
    urls_of.setdefault(path, set()).add(url)
    if not path.startswith("/static/"):
        continue                                     # /protocol.js: generated by nado.py from the constants, no imports
    for spec in SPEC.findall(COMMENTS.sub("", served(path).decode("utf-8", "replace"))):
        if spec.startswith(("https:", "http:")):
            continue                                 # three's opt-in debug hook (a dynamic import never taken here)
        r = resolve(spec, url)
        if r is None:
            unresolved.append((path, spec))
        elif r.split("?")[0].endswith((".js", ".mjs")):
            todo.append(r)

check("every import in the page's graph resolves (bare names through the import map)", not unresolved, unresolved)
twice = {p: sorted(u) for p, u in urls_of.items() if len(u) > 1}
check("no module is loaded under two URLs (two URLs = two instances)", not twice, twice)
for f in ("three.webgpu.js", "three.tsl.js", "three.core.js", "addons/tsl/display/GTAONode.js",
          "addons/tsl/display/BloomNode.js", "addons/tsl/display/FXAANode.js"):
    check(f"the page reaches /static/vendor/three/{f}", "/static/vendor/three/" + f in urls_of)
_report.done()
